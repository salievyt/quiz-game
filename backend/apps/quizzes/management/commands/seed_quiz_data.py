class Command(BaseCommand):
    help = "Seed quiz categories, questions and achievements"

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="Clear all existing data before seeding",
        )

    def handle(self, *args, **options):
        if options["clear"]:
            Question.objects.all().delete()
            Category.objects.all().delete()
            Achievement.objects.all().delete()
            self.stdout.write(self.style.WARNING("🗑  Cleared all quiz data"))

        self._seed_categories()
        self._seed_questions()
        self._seed_achievements()
        self._print_summary()
        self.stdout.write(self.style.SUCCESS("✅ Seed data loaded!"))

    # ────────── Categories ──────────

    def _seed_categories(self):
        for cat_data in CATEGORIES:
            cat, created = Category.objects.update_or_create(
                slug=cat_data["slug"],
                defaults=cat_data,
            )
            status = "+" if created else "~"
            self.stdout.write(f"  {status} Category: {cat.name}")

    # ────────── Questions ──────────

    def _seed_questions(self):
        for slug, questions in QUESTION_MAP.items():
            cat = Category.objects.filter(slug=slug).first()
            if not cat:
                self.stdout.write(self.style.WARNING(f"  ⚠ Category '{slug}' not found, skipping"))
                continue
            count = 0
            for q in questions:
                text, a, b, c, d, correct = q
                _, created = Question.objects.update_or_create(
                    category=cat,
                    text=text,
                    defaults={
                        "option_a": a,
                        "option_b": b,
                        "option_c": c,
                        "option_d": d,
                        "correct_option": correct,
                    },
                )
                if created:
                    count += 1
            self.stdout.write(f"  + {cat.name}: {len(questions)} questions ({count} new)")

    # ────────── Achievements ──────────

    def _seed_achievements(self):
        created_count = 0
        for uid, title, desc, icon, ach_type, req, rare in ACHIEVEMENTS:
            _, created = Achievement.objects.update_or_create(
                uid=uid,
                defaults={
                    "title": title,
                    "description": desc,
                    "icon": icon,
                    "achievement_type": ach_type,
                    "requirement": req,
                    "is_rare": rare,
                },
            )
            if created:
                created_count += 1
        self.stdout.write(f"  + {len(ACHIEVEMENTS)} achievements ({created_count} new)")

    # ────────── Summary ──────────

    def _print_summary(self):
        self.stdout.write("")
        self.stdout.write(self.style.HTTP_INFO("── Summary ──"))
        for cat in Category.objects.all():
            img = str(cat.image) if cat.image else '—'
            self.stdout.write(f"  {cat.name:<22s} {img:<45s} {cat.questions.count()} questions")
        total = Question.objects.count()
        self.stdout.write(self.style.SUCCESS(f"\n  Total: {Category.objects.count()} categories, {total} questions, {Achievement.objects.count()} achievements"))
